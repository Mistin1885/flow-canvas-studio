import { expect } from '@playwright/test'

export async function verifyCanvasLifecycle(owner, member, origin) {
  const { workspaces } = await (await owner.request.get(origin + '/api/catalog')).json()
  const space = workspaces[0].id
  const name = 'Return navigation test'
  const node = { id: 'Start', title: 'Start here', type: 'main', group: 'QA', decision: false, content: [] }
  const nodes = { Start: node, Jump: { ...node, id: 'Jump', type: 'return', jumpTo: 'Start' }, Middle: { ...node, id: 'Middle', type: 'action', title: 'Middle' }, End: { ...node, id: 'End', type: 'action', title: 'End' } }
  const edges = [['Start', 'Middle'], ['Middle', 'End']].map(([from, to]) => ({ from, to, kind: 'next', label: '' }))
  const { id } = await (await owner.request.post(origin + '/api/workspaces/' + space + '/canvases', {
    data: { name, graph: { schemaVersion: 1, documentType: 'dfx-project-flow', nodes, edges } },
  })).json()
  await Promise.all([owner, member].map(p => p.goto(origin + '/#canvas/' + id)))
  const a = owner.frameLocator('iframe'), b = member.frameLocator('iframe')
  const card = (frame, key) => frame.locator('.node:not(.is-leaving)[data-node-id="' + key + '"]')
  await card(a, 'Middle').locator('.branch-toggle').click()
  await expect(card(a, 'End')).toHaveCount(0)
  await card(a, 'Start').locator('.branch-toggle').click()
  await expect(card(a, 'Middle')).toHaveCount(0)
  await expect(card(b, 'End')).toBeVisible()
  await card(a, 'Start').locator('.branch-toggle').click()
  await expect(card(a, 'End')).toBeVisible()
  await a.locator('#create-node').click()
  await a.locator('#node-type').selectOption('return')
  await expect(a.locator('#node-id')).toHaveValue('RET1')
  await a.locator('#node-title').fill('Back to start')
  const target = a.getByRole('combobox', { name: '返回目標' })
  await target.fill('Start here')
  await expect(a.getByRole('option', { name: '流程入口 | Start · Start here', exact: true })).toBeVisible()
  await expect(a.getByRole('option', { name: '返回節點 | Jump · Start here', exact: true })).toHaveCount(0)
  await target.fill('end')
  const endLabel = '一般步驟 | End · End'
  await a.getByRole('option', { name: endLabel, exact: true }).click()
  await expect(target).toHaveAttribute('aria-expanded', 'false')
  await expect(target).toHaveValue(endLabel)
  await target.click()
  await target.fill('Middle')
  await target.press('Escape')
  await expect(target).toHaveValue(endLabel)
  await expect(a.locator('#node-return-target')).toHaveValue('End')
  await a.locator('#add-incoming').click()
  const incoming = a.getByRole('combobox', { name: '前序節點' })
  await incoming.fill('Start here')
  await expect(a.getByRole('option', { name: '流程入口 | Start · Start here', exact: true })).toBeVisible()
  await a.getByRole('option', { name: '返回節點 | Jump · Start here', exact: true }).click()
  await expect(incoming).toHaveAttribute('aria-expanded', 'false')
  await expect(incoming).toHaveValue('返回節點 | Jump · Start here')
  await a.locator('#added-incoming button').click()
  await a.getByRole('button', { name: '套用變更' }).click()
  const jump = b.locator('[data-node-id="RET1"] .node-body')
  await card(b, 'Start').locator('.branch-toggle').click()
  await expect(card(b, 'End')).toHaveCount(0)
  await jump.click()
  await expect(b.locator('.node.selected')).toHaveAttribute('data-node-id', 'RET1')
  await expect(card(b, 'End')).toHaveCount(0)
  await b.locator('#edit-node').click()
  await expect(b.locator('#node-id')).toHaveValue('RET1')
  await expect(b.getByRole('combobox', { name: '返回目標' })).toHaveValue(endLabel)
  await b.locator('#editor-close').click()
  await jump.dblclick()
  await expect(b.locator('#node-id')).toHaveValue('RET1')
  await b.locator('#editor-close').click()
  await b.locator('#detail .return-button').filter({ hasText: '跳轉到' }).click()
  await expect(b.locator('.node.selected')).toHaveAttribute('data-node-id', 'End')
  await a.locator('#tools-menu summary').click()
  owner.once('dialog', dialog => dialog.accept())
  await a.locator('#clear-canvas').click()
  await expect(b.locator('.node')).toHaveCount(0)
  await owner.goto(origin + '/#workspace/' + space)
  await owner.getByRole('textbox', { name: '搜尋畫布' }).fill(name)
  owner.once('dialog', dialog => dialog.accept())
  await owner.getByRole('button', { name: '刪除 ' + name }).click()
  await expect(owner.getByRole('button', { name: '刪除 ' + name })).toHaveCount(0)
  await expect(member.getByRole('alert')).toContainText('畫布已刪除')
  await owner.goto(origin + '/admin')
  const point = owner.getByRole('row').filter({ hasText: name }).filter({ hasText: 'v2' })
  await expect(point).toContainText('已刪除')
  await point.getByRole('button', { name: '還原' }).click()
  await owner.getByRole('button', { name: '確認還原' }).click()
  await expect(jump).toBeVisible()
}
